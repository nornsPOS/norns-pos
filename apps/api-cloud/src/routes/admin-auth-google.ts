/**
 * Ein kurzer, ablesbarer Code aus der Kennung.
 *
 * Er ist KEIN Geheimnis und soll keines sein. Sein Zweck ist der Vergleich:
 * das Geraet zeigt denselben Code, und wer keinen Code vor sich hat, hat auch
 * kein Geraet in diesem Vorgang — und darf nicht bestaetigen.
 */
function ablesbarerCode(nonce: string): string {
  const h = createHash('sha256').update(nonce).digest('base64url').toUpperCase();
  const nur = h.replace(/[^A-Z0-9]/g, '').replace(/[IO01]/g, 'X');
  return `${nur.slice(0, 4)}-${nur.slice(4, 8)}`;
}

