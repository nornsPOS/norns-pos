/** Random URL-safe token. */
function randomToken(): string {
  return randomBytes(32).toString('base64url');
}

/** HMAC-SHA256(payload, secret) → base64url. */
function hmac(payload: string, secret: string): string {
  return createHmac('sha256', secret).update(payload).digest('base64url');
}

/** Sign a state payload as `<base64url(json)>.<mac>`. */
function signState(p: StatePayload, secret: string): string {
  const body = Buffer.from(JSON.stringify(p)).toString('base64url');
  return `${body}.${hmac(body, secret)}`;
}

/** Verify + parse a signed state cookie. Returns null on any tamper/expiry. */
function verifyState(raw: string | undefined, secret: string): StatePayload | null {
  if (!raw) return null;
  const dot = raw.lastIndexOf('.');
  if (dot <= 0) return null;
  const body = raw.slice(0, dot);
  const mac = raw.slice(dot + 1);
  const expected = hmac(body, secret);
  if (mac.length !== expected.length) return null;
  if (!timingSafeEqual(Buffer.from(mac), Buffer.from(expected))) return null;
  try {
    const p = JSON.parse(Buffer.from(body, 'base64url').toString('utf8')) as StatePayload;
    if (!p || typeof p.exp !== 'number' || p.exp < Date.now()) return null;
    return p;
  } catch {
    return null;
  }
}

/** Decode (NOT verify-signature) a JWT's payload claims. */
function decodeJwtClaims(jwt: string): Record<string, unknown> | null {
  const parts = jwt.split('.');
  if (parts.length !== 3) return null;
  try {
    return JSON.parse(Buffer.from(parts[1] ?? '', 'base64url').toString('utf8'));
  } catch {
    return null;
  }
}

/**
 * Where the callback may hand the freshly-minted session back to. The native
 * clients cannot read an httpOnly cross-site cookie, so they open the system
 * browser at `/start?returnTo=…` and receive the token via this redirect.
 * Allowed targets ONLY:
 *   • a same-site relative path (`/…`, not `//…`)  — browser testing
 *   • the app deep-link scheme `warehouse14://…`    — Android / iOS owner app
 *   • loopback `http://localhost[:port]` / `127.0.0.1` — desktop (Tauri) app
 * Anything else is an open-redirect vector and is rejected → JSON response.
 */
function sanitizeReturnTo(v: unknown): string | null {
  if (typeof v !== 'string' || v.length === 0 || v.length > 512) return null;
  if (v.startsWith('/') && !v.startsWith('//')) return v;
  if (v.startsWith('warehouse14://')) return v;
  if (/^http:\/\/(localhost|127\.0\.0\.1)(:\d{1,5})?(\/|$)/.test(v)) return v;
  return null;
}

/** Append a URL fragment (never a query — fragments are not written to access logs). */
function withFragment(target: string, params: Record<string, string>): string {
  const frag = new URLSearchParams(params).toString();
  const sep = target.includes('#') ? '&' : '#';
  return `${target}${sep}${frag}`;
}

function redirectUriFor(baseUrl: string): string {
  return `${baseUrl.replace(/\/+$/, '')}/api/admin/auth/google/callback`;
}

const adminGoogleAuthRoutes: FastifyPluginAsync<{ env: Env }> = async (app, opts) => {
  const { env } = opts;

  function configured(): boolean {
    return !!(env.GOOGLE_STAFF_CLIENT_ID && env.GOOGLE_STAFF_CLIENT_SECRET && env.ADMIN_PUBLIC_URL);
  }

  /** Set the staff session cookie — identical attributes to routes/auth-pin.ts. */
  function setSessionCookie(reply: FastifyReply, token: string, expiresAt: Date): void {
    const crossSite = process.env.NODE_ENV === 'production';
    reply.setCookie('warehouse14.session', token, {
      httpOnly: true,
      secure: crossSite ? true : false,
      sameSite: crossSite ? 'none' : 'lax',
      path: '/',
      expires: expiresAt,
    });
  }

  // ── GET /api/admin/auth/google/start ─────────────────────────────────
  app.get(
    '/api/admin/auth/google/start',
    {
      schema: {
        tags: ['auth'],
        summary: 'Begin staff Sign-in-with-Google (302 to Google).',
        security: [],
        hide: true,
      },
    },
    async (
      req: FastifyRequest<{ Querystring: { returnTo?: string; nonce?: string } }>,
      reply: FastifyReply,
    ) => {
      if (!configured()) {
        return reply.status(503).send({
          error: { code: 'NOT_CONFIGURED', message: 'Google-Anmeldung ist nicht eingerichtet.' },
        });
      }
      const codeVerifier = randomToken();
      const codeChallenge = createHash('sha256').update(codeVerifier).digest('base64url');
      const payload: StatePayload = {
        state: randomToken(),
        codeVerifier,
        nonce: randomToken(),
        returnTo: sanitizeReturnTo(req.query.returnTo) ?? '',
        exp: Date.now() + STATE_TTL_MS,
      };
      const dn = sanitizeNonce(req.query.nonce);
      if (dn) payload.deviceNonce = dn;
      reply.setCookie(OAUTH_STATE_COOKIE, signState(payload, env.AUTH_SECRET), {
        path: OAUTH_STATE_PATH,
        httpOnly: true,
        sameSite: 'lax',
        secure: process.env.NODE_ENV === 'production',
        maxAge: Math.floor(STATE_TTL_MS / 1000),
      });

      const url = new URL(GOOGLE_AUTH_URL);
      url.searchParams.set('client_id', env.GOOGLE_STAFF_CLIENT_ID);
      url.searchParams.set('redirect_uri', redirectUriFor(env.ADMIN_PUBLIC_URL));
      url.searchParams.set('response_type', 'code');
      url.searchParams.set('scope', 'openid email profile');
      url.searchParams.set('state', payload.state);
      url.searchParams.set('nonce', payload.nonce);
      url.searchParams.set('code_challenge', codeChallenge);
      url.searchParams.set('code_challenge_method', 'S256');
      url.searchParams.set('access_type', 'online');
      url.searchParams.set('prompt', 'select_account');
      // Hint Google to pre-select the Workspace org. Not a security boundary
      // (the org-restricted consent screen + the users-table lookup are), just UX.
      if (env.STAFF_GOOGLE_HD) url.searchParams.set('hd', env.STAFF_GOOGLE_HD);
      return reply.redirect(url.toString());
    },
  );

  // ── GET /api/admin/auth/google/callback ──────────────────────────────
  app.get(
    '/api/admin/auth/google/callback',
    {
      schema: {
        tags: ['auth'],
        summary: 'Staff Google OAuth callback — exchange code, resolve role, sign in.',
        security: [],
        hide: true,
      },
    },
    async (
      req: FastifyRequest<{ Querystring: { code?: string; state?: string; error?: string } }>,
      reply: FastifyReply,
    ) => {
      if (!configured()) {
        return reply.status(503).send({
          error: { code: 'NOT_CONFIGURED', message: 'Google-Anmeldung ist nicht eingerichtet.' },
        });
      }

      const raw = (req.cookies as Record<string, string | undefined>)?.[OAUTH_STATE_COOKIE];
      reply.clearCookie(OAUTH_STATE_COOKIE, { path: OAUTH_STATE_PATH });

      const q = req.query;
      const st = verifyState(raw, env.AUTH_SECRET);
      const returnTo = st ? sanitizeReturnTo(st.returnTo) : null;

      /** Deny: return-to-app page with an error fragment, else a JSON status.
       *  Dieselbe Knopf-Seite wie der Erfolgsweg, aus demselben Grund: ein
       *  automatischer Sprung zum App-Schema wird ohne Geste blockiert. */
      const deny = (status: number, code: string, message: string) => {
        if (returnTo) {
          return sendAppReturnPage(
            reply,
            withFragment(returnTo, { error: code }),
            'Anmeldung nicht m&ouml;glich',
            'Die Anmeldung wurde nicht abgeschlossen. Zur&uuml;ck zur App:',
          );
        }
        return reply.status(status).send({ error: { code, message } });
      };

      if (q.error || !q.code || !q.state) return deny(400, 'OAUTH_FAILED', 'Anmeldung abgebrochen.');
      if (!st || st.state !== q.state) return deny(400, 'OAUTH_FAILED', 'Ungültiger Anmeldeversuch.');

      // Exchange the code SERVER-SIDE (client secret + PKCE verifier).
      let claims: Record<string, unknown> | null = null;
      try {
        const tokenResp = await fetch(GOOGLE_TOKEN_URL, {
          method: 'POST',
          headers: { 'content-type': 'application/x-www-form-urlencoded' },
          body: new URLSearchParams({
            code: q.code,
            client_id: env.GOOGLE_STAFF_CLIENT_ID,
            client_secret: env.GOOGLE_STAFF_CLIENT_SECRET,
            redirect_uri: redirectUriFor(env.ADMIN_PUBLIC_URL),
            grant_type: 'authorization_code',
            code_verifier: st.codeVerifier,
          }),
          signal: AbortSignal.timeout(10_000),
        });
        if (!tokenResp.ok) return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');
        const tokens = (await tokenResp.json()) as { id_token?: string };
        if (!tokens.id_token) return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');
        claims = decodeJwtClaims(tokens.id_token);
      } catch {
        return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');
      }
      if (!claims) return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');

      // Verify the id_token claims (token came DIRECTLY from Google over TLS, so
      // per OIDC Core §3.1.3.7 signature re-verification is not strictly required;
      // we still verify iss / aud / exp / nonce / email_verified).
      const iss = String(claims.iss ?? '');
      if (iss !== 'https://accounts.google.com' && iss !== 'accounts.google.com') {
        return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');
      }
      if (String(claims.aud ?? '') !== env.GOOGLE_STAFF_CLIENT_ID) {
        return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');
      }
      const exp = typeof claims.exp === 'number' ? claims.exp : 0;
      if (exp * 1000 < Date.now()) return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');
      if (String(claims.nonce ?? '') !== st.nonce) {
        return deny(400, 'OAUTH_FAILED', 'Anmeldung fehlgeschlagen.');
      }

      const email = String(claims.email ?? '')
        .trim()
        .toLowerCase();
      const emailVerified = claims.email_verified === true || claims.email_verified === 'true';
      const sub = String(claims.sub ?? '');
      if (!email || !emailVerified || !sub) {
        return deny(403, 'FORBIDDEN', 'Dieses Konto ist nicht freigeschaltet.');
      }

      // THE AUTHORISATION GATE: the email must resolve to an ACTIVE staff row.
      // Not found (or soft-deleted) → 403. Nothing is created here, ever.
      const staff = await app.db.query.users.findFirst({
        where: (u) => and(eq(u.email, email), isNull(u.softDeletedAt)),
        columns: { id: true, role: true, isOwner: true, preferredLanguage: true },
      });
      if (!staff) {
        const ip = req.ip ?? null;
        await app.db.insert(auditLog).values({
          eventType: 'auth.google_denied',
          actorUserId: null,
          deviceId: null,
          ipAddress: ip,
          userAgent: (req.headers['user-agent'] as string | undefined) ?? null,
          payload: { email, reason: 'not_provisioned' },
        });
        return deny(403, 'FORBIDDEN', 'Dieses Konto ist nicht freigeschaltet.');
      }

      // Mint the session — identical shape to routes/auth-pin.ts. Google login is
      // a full fresh authentication, so stamp a fresh step-up. No device binding:
      // the Google path does not carry mTLS device identity (device_id stays null).
      const ttlMs = sessionTtlMs(staff.isOwner);
      const sessionId = randomUUID();
      const token = randomUUID().replace(/-/g, '') + randomUUID().replace(/-/g, '');
      const expiresAt = new Date(Date.now() + ttlMs);
      const ip = req.ip ?? null;
      const userAgent = (req.headers['user-agent'] as string | undefined) ?? null;

      await app.db.transaction(async (tx) => {
        await tx.insert(sessions).values({
          id: sessionId,
          userId: staff.id,
          token,
          expiresAt,
          ipAddress: ip,
          userAgent,
          deviceId: null,
          lastPinStepUpAt: new Date(),
        });
        await tx.insert(auditLog).values({
          eventType: 'auth.google_login',
          actorUserId: staff.id,
          deviceId: null,
          ipAddress: ip,
          userAgent,
          payload: { email, sub, isOwner: staff.isOwner, role: staff.role },
        });
      });

      setSessionCookie(reply, token, expiresAt);

      const sessionExpiresAt = expiresAt.toISOString();
      const actor = { id: staff.id, role: staff.role, isOwner: staff.isOwner };

      // The verified Google identity for the header profile. `name`/`picture`
      // come from the `profile` scope; keep them null-safe (a Workspace account
      // may omit either). This is display-only — authority is `actor`, above.
      const displayName =
        typeof claims.name === 'string' && claims.name.trim() ? claims.name.trim() : null;
      const avatarUrl =
        typeof claims.picture === 'string' && claims.picture.trim() ? claims.picture.trim() : null;
      const profile = { email, displayName, avatarUrl };

      // (1) Native device-handoff: park the session under the nonce so the app
      // can retrieve it via POST /claim. NOT exclusive with the deep link below:
      // a mobile client may send BOTH (nonce as the robust path, returnTo as the
      // fast path) — park first, then fall through to the redirect page.
      if (st.deviceNonce) {
        const now = Date.now();
        sweepHandoffs(now);
        // NICHT mehr direkt in `handoffs`. Erst muss ein Mensch bestaetigen,
        // dass er wirklich ein GERAET anmelden wollte. Siehe die Erklaerung
        // bei `pendingConfirm`.
        // ⚠️ Die Bestaetigung gehoert dem Browser, der sich GERADE angemeldet
        // hat. Ohne diese Bindung genuegte die Kennung, und die kennt der
        // Angreifer per Konstruktion — er hat sie ja gewaehlt. Siehe
        // lib/uebergabe-browserbindung.ts.
        const bindung = neueBrowserbindung();
        pendingConfirm.set(st.deviceNonce, {
          token,
          actor,
          profile,
          sessionExpiresAt,
          createdAt: now,
          browserAbdruck: bindung.abdruck,
        });
        reply.setCookie(
          ADMIN_UEBERGABE_KEKS,
          bindung.geheimnis,
          keksOptionen(ADMIN_KEKS_PFAD, env.NODE_ENV === 'production'),
        );
        reply.header('content-type', 'text/html; charset=utf-8');
        return reply.send(confirmPage(st.deviceNonce, email, returnTo ?? ''));
      }

      // (2) Browser-redirect handoff (a mobile deep link): token in the URL
      // fragment (never the query string, so it is not written to any access log).
      //
      // NICHT als nacktes 302: Chrome auf Android blockiert eine automatische
      // Navigation zu einem App-Schema ohne Nutzergeste — der Custom Tab blieb
      // auf einer leeren Seite haengen und die Anmeldung "klemmte" (Basels
      // Befund, 24.07.2026, zwei Updates in Folge). Stattdessen eine Seite, die
      // die automatische Weiterleitung VERSUCHT und immer einen sichtbaren
      // Knopf traegt: das Tippen ist die Geste, die Chrome nie blockiert.
      if (returnTo) {
        return sendAppReturnPage(
          reply,
          withFragment(returnTo, { token, expiresAt: sessionExpiresAt }),
          'Angemeldet',
          'Sie sind angemeldet. Zur&uuml;ck zur App:',
        );
      }

      // (3) Plain browser test: the same JSON shape as pin-login.
      return { ok: true as const, sessionExpiresAt, actor, profile, token };
    },
  );

  // ── POST /api/admin/auth/google/confirm ──────────────────────────────
  //
  // Der Klick, der die Sitzung freigibt. Bis zum 26.07.2026 gab es ihn nicht:
  // die Sitzung lag abholbereit, sobald Google fertig war, und wer die Kennung
  // kannte, nahm sie. Die Kennung durfte der AUFRUFER waehlen — also wusste sie
  // ein Angreifer per Konstruktion.
  //
  // Diese Route verlangt nichts Geheimes, und das ist Absicht: sie wird aus der
  // Bestaetigungsseite heraus aufgerufen, im Browser des Menschen, der sich
  // gerade angemeldet hat. Der Schutz ist nicht ein Geheimnis, sondern die
  // ENTSCHEIDUNG: der Mensch liest, dass ein GERAET diese Anmeldung bekommt,
  // sieht einen Code, der auf seinem Geraet stehen muesste, und sagt ja.
  //
  // Wer diese Route direkt aufruft, ohne die Seite gesehen zu haben, kann damit
  // nur seine EIGENE Uebergabe freigeben — er kennt ja bereits die Kennung. Er
  // gewinnt nichts, was er nicht schon hatte.
  app.post(
    '/api/admin/auth/google/confirm',
    {
      schema: {
        tags: ['auth'],
        summary: 'Confirm a device handoff after the human has seen what it does.',
        security: [],
        hide: true,
      },
    },
    async (req: FastifyRequest<{ Body: { nonce?: string; returnTo?: string } }>, reply: FastifyReply) => {
      const nonce = sanitizeNonce((req.body ?? {}).nonce);
      reply.header('content-type', 'text/html; charset=utf-8');
      if (!nonce) return reply.status(400).send(SUCCESS_PAGE);

      const now = Date.now();
      sweepHandoffs(now);
      const wartend = pendingConfirm.get(nonce);
      // ⚠️ DIE EIGENTLICHE SCHRANKE. Vorher stand hier nur die Kennung, und
      // die kennt der Angreifer, weil er sie gewaehlt hat: `POST /confirm`
      // plus `POST /claim` genuegten, ganz ohne Menschen. An der offenen
      // Adresse gemessen: 200.
      //
      // Der Keks wird beim Google-Ruecklauf gesetzt und ist `httpOnly` samt
      // `SameSite=Lax`. Wer nur die Kennung hat, hat ihn nicht, und ein
      // fremder POST von einer Angreiferseite fuehrt ihn nicht mit.
      if (wartend && !bindungStimmt(req.cookies?.[ADMIN_UEBERGABE_KEKS], wartend.browserAbdruck)) {
        req.log.warn(
          { code: ablesbarerCode(nonce), hatKeks: Boolean(req.cookies?.[ADMIN_UEBERGABE_KEKS]) },
          'auth.device_handoff.confirm_ohne_browserbindung',
        );
        // Dieselbe Seite wie bei „abgelaufen": fuer einen Probierenden gibt es
        // hier nichts zu lernen.
        return reply.send(SUCCESS_PAGE);
      }
      if (!wartend) {
        // Abgelaufen oder schon bestaetigt. Kein Grund, hier verschiedene
        // Faelle zu unterscheiden: fuer den Menschen sieht beides gleich aus,
        // und fuer einen Probierenden gibt es so nichts zu lernen.
        return reply.send(SUCCESS_PAGE);
      }
      pendingConfirm.delete(nonce);
      reply.clearCookie(ADMIN_UEBERGABE_KEKS, { path: ADMIN_KEKS_PFAD });
      handoffs.set(nonce, wartend);
      req.log.info(
        { actorId: wartend.actor?.id ?? null, code: ablesbarerCode(nonce) },
        'auth.device_handoff.confirmed',
      );
      return reply.send(SUCCESS_PAGE);
    },
  );

  // ── POST /api/admin/auth/google/claim ────────────────────────────────
  // A native client that began login with ?nonce=… polls here to retrieve the
  // minted session exactly once. 200 + session when ready; 202 while the browser
  // leg is still in flight. The nonce is deleted on the first success (single-use),
  // and the unguessable nonce itself is the capability — no session is required.
  app.post(
    '/api/admin/auth/google/claim',
    {
      schema: {
        tags: ['auth'],
        summary: 'Claim a completed device-handoff Google login (native clients).',
        security: [],
        hide: true,
      },
    },
    async (req: FastifyRequest<{ Body: { nonce?: string } }>, reply: FastifyReply) => {
      const nonce = sanitizeNonce((req.body ?? {}).nonce);
      if (!nonce) {
        return reply
          .status(400)
          .send({ error: { code: 'BAD_REQUEST', message: 'nonce fehlt oder ist ungültig.' } });
      }
      const now = Date.now();
      sweepHandoffs(now);
      const h = handoffs.get(nonce);
      if (!h) {
        // Not ready yet (or already claimed / expired) — the client keeps polling.
        // A 200 (not 202) keeps every HTTP client's "success" path simple.
        return { ok: false as const, pending: true };
      }
      handoffs.delete(nonce); // single-use
      return {
        ok: true as const,
        sessionExpiresAt: h.sessionExpiresAt,
        actor: h.actor,
        profile: h.profile,
        token: h.token,
      };
    },
  );

  // 14.08.2026: hier stand der Weg /api/admin/auth/google/native. Sein
  // einziger Rufer war die Inhaber-App aus warehouse14, und die ist mit
  // der Trennung gefallen. Die Kasse meldet sich ueber start/callback an.
};

