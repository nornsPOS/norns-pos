/** Device-handoff window: how long a completed login waits to be claimed. */
const HANDOFF_TTL_MS = 5 * 60 * 1000; // 5 minutes

interface StatePayload {
  state: string;
  codeVerifier: string;
  nonce: string;
  returnTo: string;
  /**
   * Optional opaque device-handoff key generated by a NATIVE client (desktop /
   * mobile) that cannot receive a browser redirect. When present, the callback
   * parks the minted session under this key instead of redirecting, and the app
   * retrieves it once via POST /claim. This is the OAuth device-grant shape
   * (RFC 8628-style) adapted to our server-brokered flow — no loopback listener
   * and no custom URL scheme is required on the client.
   */
  deviceNonce?: string;
  exp: number;
}

/** A completed-but-unclaimed login, keyed by the client's deviceNonce. */
interface Handoff {
  /**
   * SHA-256 des Geheimnisses, das beim Google-Ruecklauf als `httpOnly`-Keks in
   * den Browser ging. `/confirm` verlangt es.
   *
   * ⚠️ Hier liegt bewusst nur der ABDRUCK. Sonst stuende in einem
   * Speicherabzug oder einem versehentlichen Protokollsatz das Geheimnis
   * selbst. Siehe lib/uebergabe-browserbindung.ts.
   */
  browserAbdruck?: string;

  token: string;
  actor: { id: string; role: string; isOwner: boolean };
  /** The verified Google identity, for the header profile (never an auth secret). */
  profile: { email: string; displayName: string | null; avatarUrl: string | null };
  sessionExpiresAt: string;
  createdAt: number;
}

/**
 * In-memory device-handoff store. A handoff lives for at most HANDOFF_TTL_MS and
 * is single-use (deleted on claim). In-memory is correct here: it is a few-second
 * bridge between the browser finishing consent and the native app polling /claim;
 * on the rare API restart mid-login the user simply signs in again. The token
 * itself is a real, persisted `sessions` row — only the short-lived NONCE→token
 * pointer is in memory. The nonce (>= 16 random chars) is the capability.
 */
const handoffs = new Map<string, Handoff>();

/**
 * ⚠️ NOCH NICHT BESTAETIGTE UEBERGABEN.
 *
 * Der Angriff, der diesen Zwischenschritt noetig macht, braucht keinen
 * Fehler in unserer Kryptografie:
 *
 *   1. Der Angreifer waehlt eine Kennung N und schickt dem Opfer einen Link
 *      auf `/start?nonce=N`. Der Link zeigt auf die ECHTE Firmenadresse und
 *      sieht vollkommen unverdaechtig aus.
 *   2. Das Opfer meldet sich mit seinem ECHTEN Google-Konto an.
 *   3. Der Angreifer holt die fertige Sitzung mit `POST /claim { nonce: N }`.
 *      Ohne Anmeldung, ohne Geraet, ohne alles.
 *
 * Der Kommentar an `/claim` sagte, die unerratbare Kennung SEI die Berechtigung.
 * Das stimmt nur, solange der SERVER sie erzeugt. Waehlt der Aufrufer sie, weiss
 * der Angreifer sie per Konstruktion.
 *
 * Und eine servergenerierte Kennung allein hilft nicht: der Angreifer kann sich
 * selbst eine holen und DIESE verschicken.
 *
 * Was wirklich schuetzt, ist das, was RFC 8628 hat und uns fehlte: **ein Mensch
 * sieht, was er freigibt, und sagt ja.** Der Kommentar nannte den Weg
 * „RFC 8628-style", aber dort erzeugt der Server den Code UND der Mensch
 * bestaetigt ihn sichtbar. Beides fehlte.
 *
 * Deshalb landet eine fertige Anmeldung ab dem 26.07.2026 zuerst HIER und
 * wandert erst nach einem ausdruecklichen Klick nach `handoffs`. Die Apps
 * muessen dafuer nicht geaendert werden: sie pollen weiter und bekommen so
 * lange `pending`, bis der Mensch bestaetigt hat.
 */
const pendingConfirm = new Map<string, Handoff>();

/** Opaque nonce from a native client — accept only a plausible URL-safe token. */
function sanitizeNonce(v: unknown): string | null {
  if (typeof v !== 'string') return null;
  if (v.length < 16 || v.length > 128) return null;
  return /^[A-Za-z0-9_-]+$/.test(v) ? v : null;
}

/** Drop expired handoffs (called opportunistically on each store/claim). */
function sweepHandoffs(now: number): void {
  for (const [k, v] of pendingConfirm) {
    if (now - v.createdAt > HANDOFF_TTL_MS) pendingConfirm.delete(k);
  }
  for (const [k, h] of handoffs) {
    if (now - h.createdAt > HANDOFF_TTL_MS) handoffs.delete(k);
  }
}

